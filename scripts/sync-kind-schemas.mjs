#!/usr/bin/env node
// Embeds schema/v1/kinds/*.schema.json into the Python and TypeScript reference
// validators, which ship without the repository's schema directory.
// `--check` fails when an embedded copy has drifted from the schema files.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const kindsDir = join(root, 'schema', 'v1', 'kinds')

const schemas = {}
for (const file of readdirSync(kindsDir).filter(f => f.endsWith('.schema.json')).sort()) {
  schemas[file.replace('.schema.json', '')] = JSON.parse(readFileSync(join(kindsDir, file), 'utf8'))
}
const json = JSON.stringify(schemas, null, 2)
const header = 'Generated by scripts/sync-kind-schemas.mjs from schema/v1/kinds. Do not edit by hand.'

const outputs = {
  'reference-impls/typescript/src/kind-schemas.ts':
    `// ${header}\n\nexport const KIND_SCHEMAS: Record<string, unknown> = ${json}\n`,
  'reference-impls/python/uacp/kind_schemas.py':
    `# ${header}\nimport json\n\nKIND_SCHEMAS = json.loads(r'''${json}''')\n`,
}

const check = process.argv.includes('--check')
let drift = false
for (const [path, content] of Object.entries(outputs)) {
  const target = join(root, path)
  if (check) {
    let current = ''
    try { current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n') } catch {}
    if (current !== content) {
      console.error(`${path} is out of date; run: node scripts/sync-kind-schemas.mjs`)
      drift = true
    }
  } else {
    writeFileSync(target, content)
    console.log(`wrote ${path}`)
  }
}
if (drift) process.exit(1)
if (check) console.log('kind schemas embedded in the reference validators are up to date')
